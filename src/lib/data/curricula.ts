export const CURRICULUM_MAP: Record<string, Curriculum> = Object.fromEntries(
  CURRICULA.map((c) => [c.code, c]),
) as Record<Curriculum["code"], Curriculum>;

export function findSubtopic(
  nodeId: string,
): { curriculum: Curriculum; subject: Subject; chapter: Chapter; subtopic: SubTopic } | null {
  for (const curriculum of CURRICULA) {
    for (const subject of curriculum.subjects) {
      for (const chapter of subject.chapters) {
        const subtopic = chapter.subtopics.find((s) => s.id === nodeId);
        if (subtopic) return { curriculum, subject, chapter, subtopic };
      }
    }
  }
  return null;
}

export function countQuestionsInCurriculum(curriculum: Curriculum): number {
  return curriculum.subjects.reduce(
    (acc, s) =>
      acc +
      s.chapters.reduce(
        (acc2, c) => acc2 + c.subtopics.reduce((acc3, t) => acc3 + t.availableCount, 0),
        0,
      ),
    0,
  );
}

export const TOTAL_CURRICULUM_STATS = CURRICULA.map((c) => ({
  code: c.code,
  subjects: c.subjects.length,
  chapters: c.subjects.reduce((a, s) => a + s.chapters.length, 0),
  subtopics: c.subjects.reduce(
    (a, s) => a + s.chapters.reduce((a2, chx) => a2 + chx.subtopics.length, 0),
    0,
  ),
  questions: countQuestionsInCurriculum(c),
}));

