import type {
  BloomLevel,
  Chapter,
  Curriculum,
  Difficulty,
  SubTopic,
  Subject,
} from "@/lib/types";

function st(
  id: string,
  name: string,
  learningObjectives: string[],
  bloomLevels: BloomLevel[],
  band: [Difficulty, Difficulty],
  tags: string[],
  availableCount: number,
): SubTopic {
  return {
    id,
    name,
    learningObjectives,
    bloomLevels,
    difficultyBand: band,
    tags,
    availableCount,
  };
}

function ch(id: string, name: string, subtopics: SubTopic[]): Chapter {
  return { id, name, subtopics };
}

function sub(id: string, name: string, chapters: Chapter[]): Subject {
  return { id, name, chapters };
}

